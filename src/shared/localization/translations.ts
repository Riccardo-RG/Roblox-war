export type LocalizationKey = (typeof DEFINITIONS)[number][0];
export type LocalizationArgs = Readonly<Record<string, string | number>>;

export interface LocalizedMessage {
  readonly key: LocalizationKey;
  readonly args?: LocalizationArgs;
}

export function localized(key: LocalizationKey, args?: LocalizationArgs): LocalizedMessage {
  return args === undefined ? { key } : { key, args };
}

export const LOCALIZATION_ENTRIES: ReadonlyArray<LocalizationEntry> = DEFINITIONS.map(
  ([key, english, italian, spanish, portuguese, french, german]) => ({
    Key: key,
    Source: english,
    Context: "",
    Example: "",
    Values: new Map<string, string>([
      ["en-us", english],
      ["it-it", italian],
      ["es-es", spanish],
      ["pt-br", portuguese],
      ["fr-fr", french],
      ["de-de", german],
    ]),
  }),
);

export function sourceFor(key: LocalizationKey): string {
  const definition = DEFINITIONS.find(([candidate]) => candidate === key);
  return definition?.[1] ?? key;
}

export function validateLocalizationCatalog(): void {
  const seen = new Set<string>();
  for (const entry of LOCALIZATION_ENTRIES) {
    assert(entry.Key.size() > 0, "Localization keys cannot be empty.");
    assert(!seen.has(entry.Key), `Duplicate localization key: ${entry.Key}`);
    seen.add(entry.Key);
    const sourcePlaceholders = placeholders(entry.Source);
    for (const locale of SUPPORTED_LOCALES) {
      const value = entry.Values.get(locale);
      assert(
        value !== undefined && value.size() > 0,
        `Missing ${locale} translation: ${entry.Key}`,
      );
      assert(
        placeholders(value) === sourcePlaceholders,
        `Placeholder mismatch for ${entry.Key} in ${locale}`,
      );
    }
  }
  assert(seen.size() === DEFINITIONS.size(), "Localization catalog size mismatch.");
}

function placeholders(value: string): string {
  const found = new Array<string>();
  for (const [name] of string.gmatch(value, "{([%w_]+)}")) {
    found.push(tostring(name));
  }
  found.sort();
  return found.join("|");
}
